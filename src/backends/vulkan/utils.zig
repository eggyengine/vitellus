const texture = @import("../../types/texture.zig");
const vk = @import("vulkan");

pub fn formatToVk(format: texture.Texture.Format) ?vk.Format {
    return switch (format) {
        .r8unorm => .r8_unorm,
        .r8snorm => .r8_snorm,
        .r8uint => .r8_uint,
        .r8sint => .r8_sint,

        .r16unorm => .r16_unorm,
        .r16snorm => .r16_snorm,
        .r16uint => .r16_uint,
        .r16sint => .r16_sint,
        .r16float => .r16_sfloat,
        .rg8unorm => .r8g8_unorm,
        .rg8snorm => .r8g8_snorm,
        .rg8uint => .r8g8_uint,
        .rg8sint => .r8g8_sint,

        .r32uint => .r32_uint,
        .r32sint => .r32_sint,
        .r32float => .r32_sfloat,
        .rg16unorm => .r16g16_unorm,
        .rg16snorm => .r16g16_snorm,
        .rg16uint => .r16g16_uint,
        .rg16sint => .r16g16_sint,
        .rg16float => .r16g16_sfloat,
        .rgba8unorm => .r8g8b8a8_unorm,
        .rgba8unorm_srgb => .r8g8b8a8_srgb,
        .rgba8snorm => .r8g8b8a8_snorm,
        .rgba8uint => .r8g8b8a8_uint,
        .rgba8sint => .r8g8b8a8_sint,
        .bgra8unorm => .b8g8r8a8_unorm,
        .bgra8unorm_srgb => .b8g8r8a8_srgb,

        .rgb9e5ufloat => .e5b9g9r9_ufloat_pack32,
        .rgb10a2uint => .a2b10g10r10_uint_pack32,
        .rgb10a2unorm => .a2b10g10r10_unorm_pack32,
        .rg11b10ufloat => .b10g11r11_ufloat_pack32,

        .rg32uint => .r32g32_uint,
        .rg32sint => .r32g32_sint,
        .rg32float => .r32g32_sfloat,
        .rgba16unorm => .r16g16b16a16_unorm,
        .rgba16snorm => .r16g16b16a16_snorm,
        .rgba16uint => .r16g16b16a16_uint,
        .rgba16sint => .r16g16b16a16_sint,
        .rgba16float => .r16g16b16a16_sfloat,

        .rgba32uint => .r32g32b32a32_uint,
        .rgba32sint => .r32g32b32a32_sint,
        .rgba32float => .r32g32b32a32_sfloat,

        .stencil8 => .s8_uint,
        .depth16unorm => .d16_unorm,
        .depth24plus => .d32_sfloat,
        .depth24plus_stencil8 => .d24_unorm_s8_uint,
        .depth32float => .d32_sfloat,
        .depth32float_stencil8 => .d32_sfloat_s8_uint,

        .bc1_rgba_unorm => .bc1_rgba_unorm_block,
        .bc1_rgba_unorm_srgb => .bc1_rgba_srgb_block,
        .bc2_rgba_unorm => .bc2_unorm_block,
        .bc2_rgba_unorm_srgb => .bc2_srgb_block,
        .bc3_rgba_unorm => .bc3_unorm_block,
        .bc3_rgba_unorm_srgb => .bc3_srgb_block,
        .bc4_r_unorm => .bc4_unorm_block,
        .bc4_r_snorm => .bc4_snorm_block,
        .bc5_rg_unorm => .bc5_unorm_block,
        .bc5_rg_snorm => .bc5_snorm_block,
        .bc6h_rgb_ufloat => .bc6h_ufloat_block,
        .bc6h_rgb_float => .bc6h_sfloat_block,
        .bc7_rgba_unorm => .bc7_unorm_block,
        .bc7_rgba_unorm_srgb => .bc7_srgb_block,

        .etc2_rgb8unorm => .etc2_r8g8b8_unorm_block,
        .etc2_rgb8unorm_srgb => .etc2_r8g8b8_srgb_block,
        .etc2_rgb8a1unorm => .etc2_r8g8b8a1_unorm_block,
        .etc2_rgb8a1unorm_srgb => .etc2_r8g8b8a1_srgb_block,
        .etc2_rgba8unorm => .etc2_r8g8b8a8_unorm_block,
        .etc2_rgba8unorm_srgb => .etc2_r8g8b8a8_srgb_block,
        .eac_r11unorm => .eac_r11_unorm_block,
        .eac_r11snorm => .eac_r11_snorm_block,
        .eac_rg11unorm => .eac_r11g11_unorm_block,
        .eac_rg11snorm => .eac_r11g11_snorm_block,

        .astc_4x4_unorm => .astc_4x_4_unorm_block,
        .astc_4x4_unorm_srgb => .astc_4x_4_srgb_block,
        .astc_5x4_unorm => .astc_5x_4_unorm_block,
        .astc_5x4_unorm_srgb => .astc_5x_4_srgb_block,
        .astc_5x5_unorm => .astc_5x_5_unorm_block,
        .astc_5x5_unorm_srgb => .astc_5x_5_srgb_block,
        .astc_6x5_unorm => .astc_6x_5_unorm_block,
        .astc_6x5_unorm_srgb => .astc_6x_5_srgb_block,
        .astc_6x6_unorm => .astc_6x_6_unorm_block,
        .astc_6x6_unorm_srgb => .astc_6x_6_srgb_block,
        .astc_8x5_unorm => .astc_8x_5_unorm_block,
        .astc_8x5_unorm_srgb => .astc_8x_5_srgb_block,
        .astc_8x6_unorm => .astc_8x_6_unorm_block,
        .astc_8x6_unorm_srgb => .astc_8x_6_srgb_block,
        .astc_8x8_unorm => .astc_8x_8_unorm_block,
        .astc_8x8_unorm_srgb => .astc_8x_8_srgb_block,
        .astc_10x5_unorm => .astc_1_0x_5_unorm_block,
        .astc_10x5_unorm_srgb => .astc_1_0x_5_srgb_block,
        .astc_10x6_unorm => .astc_1_0x_6_unorm_block,
        .astc_10x6_unorm_srgb => .astc_1_0x_6_srgb_block,
        .astc_10x8_unorm => .astc_1_0x_8_unorm_block,
        .astc_10x8_unorm_srgb => .astc_1_0x_8_srgb_block,
        .astc_10x10_unorm => .astc_1_0x_10_unorm_block,
        .astc_10x10_unorm_srgb => .astc_1_0x_10_srgb_block,
        .astc_12x10_unorm => .astc_1_2x_10_unorm_block,
        .astc_12x10_unorm_srgb => .astc_1_2x_10_srgb_block,
        .astc_12x12_unorm => .astc_1_2x_12_unorm_block,
        .astc_12x12_unorm_srgb => .astc_1_2x_12_srgb_block,
    };
}
